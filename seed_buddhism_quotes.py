def main():
    print(f"=== Подготовка к загрузке {len(BUDDHISM_PHRASES)} фраз о буддизме ===")
    
    # 1. Подключаемся к клиенту и индексу
    client = PineconeVectorClient(index_name="test2")
    
    namespace = "buddhism"
    print(f"Целевой индекс: '{client.current_index_name}', namespace: '{namespace}'")
    
    # 2. Формируем элементы для пакетной загрузки
    items = []
    for item in BUDDHISM_PHRASES:
        items.append({
            "id": item["id"],
            "text": item["text"],
            "metadata": {
                "topic": item["topic"],
                "author": item["author"],
                "category": "philosophy",
                "tradition": "buddhism",
            }
        })

    # 3. Векторизация через OpenRouter и загрузка в Pinecone
    print("\nГенерация эмбеддингов (OpenRouter) и пакетная запись в Pinecone...")
    result = client.upsert_texts(items=items, namespace=namespace, batch_size=30)
    print(f"Успешно загружено векторов: {result['upserted_count']} (пакетов: {result['batches_count']})")
    
    # 4. Проверяем статистику индекса
    stats = client.get_index_stats()
    print(f"\nТекущая статистика индекса: {stats}")
    
    # 5. Демонстрационный семантический поиск по загруженным фразам
    test_queries = [
        "Как избавиться от душевной боли и переживаний?",
        "Что буддизм говорит о контроле над мыслями и медитации?",
        "Почему всё в жизни постоянно меняется?",
    ]
    
    print("\n=== Проверка семантического поиска по базе ===")
    for q in test_queries:
        print(f"\nЗапрос: \"{q}\"")
        matches = client.search_by_text(query_text=q, top_k=2, namespace=namespace)
        for i, match in enumerate(matches, 1):
            score = match['score']
            meta = match.get('metadata', {})
            print(f"  {i}. [Score: {score:.4f}] ({meta.get('topic')})")
            print(f"     \"{meta.get('text')}\"")
            print(f"     — {meta.get('author')}")

if __name__ == "__main__":
    main()
